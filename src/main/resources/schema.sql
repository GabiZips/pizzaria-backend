create table if not exists clientes(
  cpf varchar(15) not null primary key,
  nome varchar(100) not null,
  celular varchar(20) not null,
  endereco varchar(255) not null,
  email varchar(255) not null
);

create table if not exists ingredientes (
  id bigint primary key,
  descricao varchar(255) not null
);

create table if not exists itensEstoque(
    id bigint primary key,
    quantidade int,
    ingrediente_id bigint,
    foreign key (ingrediente_id) references ingredientes(id)
);

-- Tabela Receita
create table if not exists receitas (
  id bigint primary key,
  titulo varchar(255) not null
);

-- Tabela de relacionamento entre Receita e Ingrediente
create table if not exists receita_ingrediente (
  receita_id bigint not null,
  ingrediente_id bigint not null,
  primary key (receita_id, ingrediente_id),
  foreign key (receita_id) references receitas(id),
  foreign key (ingrediente_id) references ingredientes(id)
);

-- Tabela de Produtos
create table if not exists produtos (
  id bigint primary key,
  descricao varchar(255) not null,
  preco bigint
);

-- Tabela de relacionamento entre Produto e Receita
create table if not exists produto_receita (
  produto_id bigint not null,
  receita_id bigint not null,
  primary key (produto_id,receita_id),
  foreign key (produto_id) references produtos(id),
  foreign key (receita_id) references receitas(id)
);

-- Tabela de Cardapios
create table if not exists cardapios (
  id bigint primary key,
  titulo varchar(255) not null
);

-- Tabela de relacionamento entre Cardapio e Produto
create table if not exists cardapio_produto (
  cardapio_id bigint not null,
  produto_id bigint not null,
  primary key (cardapio_id,produto_id),
  foreign key (cardapio_id) references cardapios(id),
  foreign key (produto_id) references produtos(id)
);
create table preferencias_pizzaria (
    id integer primary key check (id = 1),
    cardapio_id bigint not null references cardapios(id),
    desconto_codigo varchar(255) not null
);

create table produto_indisponivel (
    produto_id bigint primary key references produtos(id)
);

create table pedidos (
    id bigint generated by default as identity primary key,
    email varchar(255) not null,
    endereco varchar(255) not null,
    subtotal bigint not null,
    desconto bigint not null,
    imposto bigint not null,
    total bigint not null,
    estado varchar(255) not null,
    aprovado_em timestamp not null,
    pago_em timestamp,
    entregue_em timestamp,
    entregador varchar(255)
);

create table pedido_itens (
    pedido_id bigint not null references pedidos(id),
    posicao integer not null,
    produto_id bigint not null references produtos(id),
    quantidade integer not null,
    preco_unitario bigint not null,
    primary key (pedido_id, posicao)
);

create table pedido_reserva (
    pedido_id bigint not null references pedidos(id),
    ingrediente_id bigint not null references ingredientes(id),
    quantidade integer not null,
    primary key (pedido_id, ingrediente_id)
);

create table pedido_historico (
    pedido_id bigint not null references pedidos(id),
    posicao integer not null,
    estado varchar(255) not null,
    quando timestamp not null,
    primary key (pedido_id, posicao)
);
